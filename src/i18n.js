// Internationalisation strings and font stacks for English (en) and Vietnamese (vi).

export const FONT_EN = '"Russo One", "Arial Black", Impact, sans-serif';
export const MONO_EN = '"Share Tech Mono", ui-monospace, Menlo, monospace';
export const FONT_VI = 'system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif';

export function fontSpec(lang, size, kind = 'ui') {
  if (lang === 'vi') {
    const w = kind === 'title' ? '800 ' : kind === 'ui' ? '700 ' : '600 ';
    return `${w}${size}px ${FONT_VI}`;
  }
  return `${size}px ${kind === 'mono' ? MONO_EN : FONT_EN}`;
}

export function detectLang() {
  try {
    const saved = localStorage.getItem('steelstorm.lang');
    if (saved === 'vi' || saved === 'en') return saved;
  } catch {}
  try {
    if (typeof navigator !== 'undefined' && /^vi\b/i.test(navigator.language || '')) return 'vi';
  } catch {}
  return 'en';
}

